"""Build the citation-labelling worksheet, or score the labels once it is filled in.

    python -m eval.citation_gold_run --build
    python -m eval.citation_gold_run --score

`--build` writes three files into `eval/citation_gold/`: `pairs.jsonl` (the judgments, for
machines), `worksheet.md` (the same judgments, for reading), and `labels.jsonl` pre-seeded
with `null` for every row. Filling it in means changing each `null` to `true` or `false`.
Nothing is overwritten once `labels.jsonl` has an answer in it.

`--score` reports the human rates, and the judge's sensitivity, specificity and Cohen's
kappa measured against those labels - on the pairs that produced the published number
rather than on the proxy population the judge was calibrated against. See
`eval/citation_gold.py` for why that distinction is the whole point.

Offline and deterministic: no model is loaded. The judge's own decisions are read from
`eval/citation_correctness.json`, so scoring does not depend on a GPU being present.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from eval.citation_gold import (
    GOLD_DIR,
    LABELS,
    PAIRS,
    SUPPORT,
    WORKSHEET,
    agreement,
    build_blocks,
    gold_pairs,
    human_counts,
    load_labels,
)

OUT = ROOT / "eval" / "citation_gold.json"
STRUCTURE = ROOT / "eval" / "citation_structure.json"


def _wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson score interval, matching scripts/figures/generate_figures.py.

    Normal approximations are wrong at these counts, which is the same reason that file
    uses Wilson for the retrieval figures.
    """
    import math

    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, centre - half), min(1.0, centre + half)


def build() -> int:
    structure = json.loads(STRUCTURE.read_text(encoding="utf-8"))
    pairs = gold_pairs(structure, build_blocks())
    GOLD_DIR.mkdir(parents=True, exist_ok=True)

    PAIRS.write_text(
        "".join(json.dumps(p, ensure_ascii=False) + "\n" for p in pairs),
        encoding="utf-8",
    )

    existing = load_labels(LABELS)
    if existing:
        print(f"{LABELS.name} already holds {len(existing)} answer(s); left untouched.")
    else:
        LABELS.write_text(
            "# One row per judgment. Change each null to true or false.\n"
            "# true  = the blocks shown DO support the statement\n"
            "# false = they do not\n"
            "# Leave null for anything you have not decided; null is not a label.\n"
            + "".join(
                json.dumps({"pair_id": p["pair_id"], "supported": None}) + "\n"
                for p in pairs
            ),
            encoding="utf-8",
        )
        print(f"wrote {LABELS.relative_to(ROOT)}  ({len(pairs)} rows to fill in)")

    support = [p for p in pairs if p["kind"] == SUPPORT]
    necessity = [p for p in pairs if p["kind"] != SUPPORT]

    lines = [
        "# Citation-correctness labelling worksheet",
        "",
        "Generated by `python -m eval.citation_gold_run --build`. Do not edit by hand —",
        "record answers in `labels.jsonl` instead, by changing each `null` to `true` or",
        "`false`.",
        "",
        "These are ALCE's two judgments (Gao et al., arXiv:2305.14627) and no others.",
        "The premise text below is exactly what the metric scored: the cited blocks,",
        "concatenated in citation order.",
        "",
        f"**Part A — support ({len(support)} judgments).** Do the cited blocks, taken",
        "together, support the statement? Judge only whether the blocks *say it*, not",
        "whether it is true of flood policy generally, and not whether the answer is",
        "well written.",
        "",
        f"**Part B — necessity ({len(necessity)} judgments).** Only for sentences citing",
        "more than one block. With one block removed, do the rest still support the",
        "statement? A block whose removal breaks support was needed; one whose removal",
        "changes nothing was along for the ride. Part B rows only count where Part A",
        "said `true`, so you can skip the ones whose sentence you marked unsupported.",
        "",
        "---",
        "",
        "## Part A — does the citation support the sentence?",
        "",
    ]

    def block(p: dict[str, Any]) -> list[str]:
        cited = ", ".join(f"[{n}]" for n in p["citations"])
        out = [
            f"### `{p['pair_id']}`",
            "",
            f"*{p['question_id']}, sentence {p['sentence_index']}, cites {cited}*",
            "",
            "**Statement**",
            "",
            f"> {p['hypothesis']}",
            "",
            f"**{p['question']}**",
            "",
            "<details><summary>Blocks shown (click to expand)</summary>",
            "",
            "```text",
            p["premise"] or "(no text — the cited block was out of range)",
            "```",
            "",
            "</details>",
            "",
            f"`{{\"pair_id\": \"{p['pair_id']}\", \"supported\": null}}`",
            "",
        ]
        return out

    for p in support:
        lines += block(p)

    if necessity:
        lines += ["---", "", "## Part B — was each citation needed?", ""]
        for p in necessity:
            lines += block(p)

    WORKSHEET.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {WORKSHEET.relative_to(ROOT)}")
    print(f"wrote {PAIRS.relative_to(ROOT)}")
    print(f"\nPart A: {len(support)} judgments   Part B: {len(necessity)} judgments")
    return 0


def score() -> int:
    structure = json.loads(STRUCTURE.read_text(encoding="utf-8"))
    pairs = gold_pairs(structure, build_blocks())
    labels = load_labels(LABELS)

    if not labels:
        print(f"No labels yet in {LABELS.relative_to(ROOT)}.")
        print("Fill it in, then re-run with --score.")
        return 1

    counts = human_counts(pairs, labels)
    payload: dict[str, Any] = {
        "generated_utc": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "purpose": (
            "Human-labelled gold standard for ALCE citation correctness, and the NLI "
            "judge measured against it on the pairs that were actually scored."
        ),
        "labelled_by": "repository owner, by hand",
        "pairs": counts["pairs"],
        "support_pairs": counts["support_pairs"],
        "unlabelled": counts["unlabelled"],
        "human": {},
    }

    for name, key in (("citation_recall", "recall"), ("citation_precision", "precision")):
        c = counts[key]
        if not c:
            payload["human"][name] = None
            continue
        num, den = tuple(c.values())
        low, high = _wilson(num, den)
        payload["human"][name] = {
            "counts": c,
            "rate": round(num / den, 4) if den else None,
            "wilson_95": [round(low, 3), round(high, 3)],
        }

    # The judge's decisions on the same support pairs, read from its artefact rather than
    # recomputed, so this stays offline and cannot drift from what was published.
    correctness = json.loads(
        (ROOT / "eval" / "citation_correctness.json").read_text(encoding="utf-8")
    )
    judged = _judge_support(correctness, pairs)
    shared = [
        p["pair_id"]
        for p in pairs
        if p["kind"] == SUPPORT and p["pair_id"] in labels and p["pair_id"] in judged
    ]
    if shared:
        payload["judge_vs_human"] = {
            **agreement([labels[i] for i in shared], [judged[i] for i in shared]),
            "judge": correctness["judge"]["model"],
            "note": (
                "Measured on the cited-sentence pairs themselves. The sensitivity in "
                "citation_correctness.json's `calibration` is on a different "
                "population (gold answers against chunks) and does not transfer."
            ),
        }
    else:
        payload["judge_vs_human"] = None

    OUT.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

    print(f"labelled {len(labels)} of {counts['pairs']} judgments")
    for name, value in payload["human"].items():
        if value:
            c = value["counts"]
            print(
                f"{name:19s} {'/'.join(str(v) for v in c.values())} = {value['rate']}"
                f"   95% Wilson {value['wilson_95']}"
            )
        else:
            print(f"{name:19s} not reportable yet")
    jvh = payload["judge_vs_human"]
    if jvh:
        print(
            f"judge vs human      n={jvh['n']} kappa={jvh['kappa']} "
            f"sens={jvh['sensitivity']} spec={jvh['specificity']}"
        )
    print(f"\nwrote {OUT.relative_to(ROOT)}")
    return 0


def _judge_support(
    correctness: dict[str, Any], pairs: list[dict[str, Any]]
) -> dict[str, bool]:
    """The judge's per-sentence verdicts, read from its artefact.

    `citation_correctness_run.py` records a `sentences` list per question precisely so
    this comparison can cover every pair. Where it is absent, a per-question rate can
    only be unpicked when the question has a single cited sentence - 0.333 over three
    sentences says one was supported, not which - and the rest are omitted rather than
    guessed at, because inventing verdicts would fabricate agreement.
    """
    by_question = {r["question_id"]: r for r in correctness.get("per_question", [])}
    counts: dict[str, int] = {}
    for p in pairs:
        if p["kind"] == SUPPORT:
            counts[p["question_id"]] = counts.get(p["question_id"], 0) + 1

    out: dict[str, bool] = {}
    for p in pairs:
        if p["kind"] != SUPPORT:
            continue
        row = by_question.get(p["question_id"])
        if not row:
            continue
        decisions = {
            s["index"]: bool(s["supported"]) for s in row.get("sentences") or []
        }
        if p["sentence_index"] in decisions:
            out[p["pair_id"]] = decisions[p["sentence_index"]]
        elif counts.get(p["question_id"]) == 1 and row.get("recall") is not None:
            out[p["pair_id"]] = bool(row["recall"])
    return out


def main() -> int:
    parser = argparse.ArgumentParser(prog="citation_gold_run")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--build", action="store_true", help="write the worksheet")
    group.add_argument("--score", action="store_true", help="score the labels")
    args = parser.parse_args()
    return build() if args.build else score()


if __name__ == "__main__":
    raise SystemExit(main())
